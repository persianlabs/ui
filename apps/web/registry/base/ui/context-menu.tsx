"use client"

import { ContextMenu as ContextMenuPrimitive } from "@base-ui/react/context-menu"
import { DirectionProvider } from "@base-ui/react/direction-provider"
import { CheckIcon, ChevronRightIcon } from "lucide-react"
import * as React from "react"

import { cn } from "@/lib/utils"

/**
 * ContextMenuContent renders through a Portal, so it doesn't inherit `dir`
 * from a nearby wrapper (only from document.documentElement).
 * ContextMenuTrigger measures the ambient direction where it's actually
 * rendered and pushes it here so ContextMenuContent can apply it explicitly
 * to the portaled popup.
 *
 * The DOM `dir` attribute alone isn't enough: Base UI resolves logical
 * `side="inline-end"` values through its own internal DirectionContext, not
 * from CSS/DOM `dir`, so the tree is also wrapped in Base UI's own
 * DirectionProvider — otherwise the menu (and its submenus) always open as
 * if LTR.
 */
const ContextMenuDirContext = React.createContext<{
  dir: "ltr" | "rtl"
  setDir: (dir: "ltr" | "rtl") => void
}>({ dir: "ltr", setDir: () => {} })

function ContextMenu({ ...props }: ContextMenuPrimitive.Root.Props) {
  const [dir, setDir] = React.useState<"ltr" | "rtl">("ltr")
  const contextValue = React.useMemo(() => ({ dir, setDir }), [dir])

  return (
    <ContextMenuDirContext.Provider value={contextValue}>
      <DirectionProvider direction={dir}>
        <ContextMenuPrimitive.Root data-slot="context-menu" {...props} />
      </DirectionProvider>
    </ContextMenuDirContext.Provider>
  )
}

function ContextMenuPortal({ ...props }: ContextMenuPrimitive.Portal.Props) {
  return (
    <ContextMenuPrimitive.Portal data-slot="context-menu-portal" {...props} />
  )
}

function ContextMenuTrigger({
  className,
  ...props
}: ContextMenuPrimitive.Trigger.Props) {
  const ref = React.useRef<HTMLDivElement>(null)
  const { setDir } = React.useContext(ContextMenuDirContext)

  React.useEffect(() => {
    function update() {
      if (!ref.current) return
      setDir(getComputedStyle(ref.current).direction === "rtl" ? "rtl" : "ltr")
    }

    update()

    const observer = new MutationObserver(update)
    observer.observe(document.documentElement, {
      attributes: true,
      attributeFilter: ["dir"],
      subtree: true,
    })

    return () => observer.disconnect()
  }, [setDir])

  return (
    <ContextMenuPrimitive.Trigger
      ref={ref}
      data-slot="context-menu-trigger"
      className={cn("select-none", className)}
      {...props}
    />
  )
}

function ContextMenuContent({
  className,
  align = "start",
  alignOffset = 4,
  side = "inline-end",
  sideOffset = 0,
  ...props
}: ContextMenuPrimitive.Popup.Props &
  Pick<
    ContextMenuPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset"
  >) {
  const { dir } = React.useContext(ContextMenuDirContext)

  return (
    <ContextMenuPrimitive.Portal>
      <ContextMenuPrimitive.Positioner
        dir={dir}
        className="isolate z-50 outline-none"
        align={align}
        alignOffset={alignOffset}
        side={side}
        sideOffset={sideOffset}
      >
        <ContextMenuPrimitive.Popup
          data-slot="context-menu-content"
          className={cn(
            "z-50 max-h-(--available-height) min-w-36 origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-lg border border-border bg-popover p-1 text-popover-foreground shadow-md outline-none duration-150 data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95",
            className
          )}
          {...props}
        />
      </ContextMenuPrimitive.Positioner>
    </ContextMenuPrimitive.Portal>
  )
}

