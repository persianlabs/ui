export interface IsValidNationalIdOptions {
  /**
   * Also verify the first 3 digits against the known issuance-office prefix
   * list. Rejects malformed-but-checksum-valid values, at the cost of a
   * false negative on any prefix issued after this list was last updated —
   * pass `false` if you'd rather skip that risk and rely on the checksum
   * alone.
   *
   * @default true
   */
  checkPrefix?: boolean
}

/**
 * Validates an Iranian national ID (کد ملی).
 *
 * - Accepts 8-10 digit input; shorter values are zero-padded on the left,
 *   matching systems that store the code without leading zeros.
 * - Rejects an all-zero value and any repeated-digit sequence (e.g.
 *   "1111111111").
 * - Rejects a value whose 6 middle digits (positions 4-9) are all zero.
 * - Verifies the 10th digit against the standard weighted checksum: each of
 *   the first 9 digits is weighted by (10 - index), the weighted sum is
 *   taken mod 11, and the result must match the check digit — with the
 *   well-known edge case that a remainder under 2 expects the check digit
 *   to equal the remainder itself, rather than 11 - remainder.
 * - By default, also verifies the 3-digit prefix against known
 *   issuance-office codes (see `checkPrefix`).
 *
 * @example
 * isValidNationalId("0499370899") // true
 * isValidNationalId("499370899") // true — zero-padded to "0499370899"
 * isValidNationalId("۰۴۹۹۳۷۰۸۹۹") // true — Persian digits normalized first
 * isValidNationalId("0000000000") // false — all zeros
 * isValidNationalId("1111111111") // false — repeated digits
 * isValidNationalId("0499370898") // false — bad checksum
 */
export function isValidNationalId(
  value: string | null | undefined,
  options: IsValidNationalIdOptions = {}
): boolean {
  const { checkPrefix = true } = options
  const digits = normalizePersianDigits(value ?? "").replace(/\D/g, "")

  if (digits.length < 8 || digits.length > 10) return false
  if (Number(digits) === 0) return false

  const padded = digits.padStart(10, "0")

  if (/^(\d)\1{9}$/.test(padded)) return false
  if (Number(padded.slice(3, 9)) === 0) return false
  if (checkPrefix && !VALID_NATIONAL_ID_PREFIXES.has(padded.slice(0, 3))) {
    return false
  }

  const check = Number(padded[9])
  const sum = padded
    .slice(0, 9)
    .split("")
    .reduce((total, digit, index) => total + Number(digit) * (10 - index), 0)
  const remainder = sum % 11

  return remainder < 2 ? check === remainder : check === 11 - remainder
}
